"""Generate only the new context catalog/profile from the scoped CSV evidence.
No DLL execution, runtime scanning, game fingerprint assertion or network use.
"""
from pathlib import Path
import csv
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).resolve().parent
SRC = ROOT / 'source/reconstructed'
INPUT = ROOT / 'source/offset_inventory/manual_update_offsets.csv'


def quoted(value):
    return json.dumps(value, ensure_ascii=True)


def generate():
    rows = list(csv.DictReader(INPUT.open()))
    entries = []
    for index, row in enumerate(rows, 2):
        is_rva = row['category'] == 'hardcoded_gameassembly_rva'
        contexts = row['native_sites'].split(';') if is_rva else row['context'].split('; ')
        for context in contexts:
            if is_rva:
                key = 'gameassembly.site_' + context.removeprefix('0x')
            elif context.startswith('guarded game-field getter '):
                key = 'field.getter_' + context.split('0x')[1]
            else:
                slug = context.replace('.cpp:', '.').replace('_analysis', '')
                slug = re.sub(r'[^a-zA-Z0-9_.]+', '_', slug).strip('_').lower()
                key = 'field.' + slug + '.' + row['offset'].removeprefix('0x')
            entry = dict(key=key, kind='module_rva' if is_rva else 'field_offset',
                         module='GameAssembly.dll' if is_rva else '',
                         reference_value=row['offset'], context=context,
                         inventory_csv_line=index, inventory_row=row)
            entries.append(entry)
    assert len({e['key'] for e in entries}) == len(entries)
    entries.sort(key=lambda e: e['key'])
    getter_map = {int(e['key'].split('_')[-1], 16): e['key'] for e in entries
                  if e['key'].startswith('field.getter_')}
    assert len(getter_map) == 28
    direct_map = {}
    for line in (SRC / 'game_direct_wrappers_specs.inc').read_text().splitlines():
        numbers = re.findall(r'0x[0-9a-f]+', line)
        if not numbers:
            continue
        wrapper, end = map(lambda s: int(s, 16), numbers[:2])
        candidates = [e for e in entries if e['kind'] == 'module_rva'
                      and wrapper <= int(e['context'], 16) < end]
        assert len(candidates) == 1
        assert int(candidates[0]['reference_value'], 16) == int(numbers[5], 16)
        direct_map[wrapper] = candidates[0]['key']
    assert len(direct_map) == 18

    cpp = ['// Generated by menu_offsets/catalog/generate_catalog.py; see catalog.json.',
           '#include "offset_catalog.hpp"', 'namespace re_base {',
           'std::span<const OffsetCatalogSpec> offset_catalog_specs() {',
           '    static constexpr OffsetCatalogSpec specs[]{']
    for e in entries:
        evidence = e['inventory_row']['evidence_file'] + ':' + e['inventory_row']['evidence_lines']
        description = ('Historical native GameAssembly reference at ' if e['kind'] == 'module_rva'
                       else 'Historical receiver context: ') + e['context']
        cpp.append('        {' + ', '.join([quoted(e['key']), 'OffsetKind::'+e['kind'],
                   quoted(e['module']), e['reference_value'], quoted(evidence), quoted(description)]) + '},')
    cpp += ['    };', '    return specs;', '}',
            'ProfileResult validate_catalog_profile(const OffsetProfile &profile) {',
            '    if (auto result = validate_offset_profile(profile); !result) return result;',
            '    for (const auto &spec : offset_catalog_specs()) {',
            '        const auto it = profile.offsets.find(std::string(spec.key));',
            '        if (it == profile.offsets.end())',
            '            return {ProfileError::missing_key, "Missing catalog key: " + std::string(spec.key)};',
            '        if (it->second.kind != spec.kind)',
            '            return {ProfileError::kind_mismatch, "Wrong kind: " + std::string(spec.key)};',
            '        if (it->second.module != spec.module)',
            '            return {ProfileError::module_mismatch, "Wrong module: " + std::string(spec.key)};',
            '    }', '    return {};', '}',
            'OffsetProfile historical_offset_profile() {', '    OffsetProfile profile;',
            '    profile.profile_id = "historical-cheat-sample-unverified-v1";',
            '    profile.game_build = "unknown-historical-build-unverified";',
            '    profile.provenance = "Scoped recovered fixed inputs from cheat.unpacked.dll SHA256 ad5ad10d4fbb818064a4d1ce245c6c586394026c2296c94d2eb99e7487ee2090; game binaries and metadata unavailable; historical/unverified";',
            '    profile.modules.emplace("GameAssembly.dll", ModuleIdentity{});',
            '    profile.modules.emplace("UnityPlayer.dll", ModuleIdentity{});',
            '    for (const auto &spec : offset_catalog_specs())',
            '        profile.offsets.emplace(std::string(spec.key), OffsetEntry{spec.kind, std::string(spec.module), spec.reference_value});',
            '    return profile;', '}', '}']
    (SRC / 'offset_catalog.cpp').write_text('\n'.join(cpp)+'\n')
    profile = dict(schema_version=1, profile_id='historical-cheat-sample-unverified-v1',
                   game_build='unknown-historical-build-unverified',
                   provenance='Scoped recovered fixed inputs from cheat.unpacked.dll SHA256 ad5ad10d4fbb818064a4d1ce245c6c586394026c2296c94d2eb99e7487ee2090; game binaries and metadata unavailable; historical/unverified',
                   modules={name: dict(sha256='', image_size=0) for name in ('GameAssembly.dll', 'UnityPlayer.dll')},
                   offsets={e['key']: dict(kind=e['kind'], module=e['module'], value=e['reference_value']) for e in entries})
    (ROOT / 'source/windows_base/offsets.json').write_text(json.dumps(profile, indent=2)+'\n')
    metadata = dict(definition='Context-expanded scoped historical inventory; not a global inventory.',
                    field_context_entries=sum(e['kind']=='field_offset' for e in entries),
                    module_reference_entries=sum(e['kind']=='module_rva' for e in entries),
                    distinct_field_values=len({e['reference_value'] for e in entries if e['kind']=='field_offset'}),
                    distinct_module_rvas=len({e['reference_value'] for e in entries if e['kind']=='module_rva'}),
                    audited_getter_keys=len(getter_map), direct_wrapper_key_count=len(direct_map),
                    evidence_attribution='CSV field rows aggregate native/source sites across all contexts; no one-to-one native attribution is inferred.',
                    inputs={str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                            for p in [INPUT, SRC/'field_getters_analysis.cpp', SRC/'game_direct_wrappers_specs.inc', ROOT/'source/offset_inventory/summary.json']},
                    direct_wrapper_keys={hex(r): k for r,k in sorted(direct_map.items())}, entries=entries)
    (OUT / 'catalog.json').write_text(json.dumps(metadata, indent=2)+'\n')
    # These mappings are appended to the handwritten bindings implementation.
    return getter_map, direct_map


if __name__ == '__main__':
    getters, directs = generate()
    binding = SRC / 'offset_profile_bindings.cpp'
    marker = '// Generated context mappings.\n'
    text = binding.read_text().split(marker)[0]
    getter_source = (SRC / 'field_getters_analysis.cpp').read_text()
    descriptors = re.search(r'static constexpr std::array<FieldGetterSpec,28> specs\{\{(.*?)\}\};', getter_source, re.S).group(1)
    text = re.sub(r'// BEGIN OWNED GETTER DESCRIPTORS.*?// END OWNED GETTER DESCRIPTORS',
                  '// BEGIN OWNED GETTER DESCRIPTORS\n    static constexpr FieldGetterSpec specs[]{' + descriptors +
                  '    };\n    // END OWNED GETTER DESCRIPTORS', text, flags=re.S)
    for name, mapping in [('profile_field_key', getters), ('profile_direct_key', directs)]:
        if name == 'profile_field_key':
            text += marker
        text += f'std::string_view {name}(Rva r) {{\n    switch (r) {{\n'
        for r, key in sorted(mapping.items()):
            text += f'    case {hex(r)}: return {quoted(key)};\n'
        text += '    default: return {};\n    }\n}\n'
    binding.write_text(text + '} // namespace rust_internal_re\n')
