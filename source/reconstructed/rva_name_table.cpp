const RvaNameEntry* rva_name_lookup(Rva rva) {
    // [I] Linear scan; table is small enough that binary search is unnecessary.
    for (ReUSize i = 0; i < table_count; ++i)
        if (table[i].rva == rva) return &table[i];
    return nullptr;
}

re::ReString rva_name_format(Rva rva) {
    const auto* entry = rva_name_lookup(rva);
    re::ReString result;
    if (entry) {
        result = re::ReString(entry->name.data(), entry->name.size());
        result.push_back(' ');
        result.push_back('(');
    }
    // [I] Format hex RVA as 0xXXXXXX.
    result.push_back('0');
    result.push_back('x');
    const char hex[] = "0123456789abcdef";
    bool started = false;
    for (int shift = 28; shift >= 0; shift -= 4) {
        const char c = hex[(rva >> shift) & 0xf];
        if (c != '0' || started || shift == 0) {
            result.push_back(c);
            started = true;
        }
    }
    if (entry) result.push_back(')');
    return result;
}

void check_rva_name_table() {
    const auto t = rva_name_table();
    // [I] Verify table is non-empty and entries have valid fields.
    if (t.empty()) __builtin_trap();
    for (ReUSize i = 0; i < t.size(); ++i) {
        if (t[i].rva == 0) __builtin_trap();
        if (t[i].name.empty()) __builtin_trap();
        if (t[i].category.empty()) __builtin_trap();
    }
    // [I] Verify lookup works for known entries.
    const auto* p = rva_name_lookup(0x369164);
    if (!p) __builtin_trap();
    if (p->name != re::ReStringView("get_position")) __builtin_trap();
    // [I] Verify unknown RVA returns nullptr.
    if (rva_name_lookup(0xdeadbeef)) __builtin_trap();
    // [I] Verify format output.
    const auto fmt = rva_name_format(0x369164);
    if (fmt.empty()) __builtin_trap();
    const auto unk = rva_name_format(0x999999);
    if (unk.empty()) __builtin_trap();
}
