re::ReSpan<const ConfigKeyEntry> config_catalog() {
    return {catalog_table, catalog_count};
}

const ConfigKeyEntry* config_lookup(Rva value_address) {
    ReUSize lo = 0, hi = catalog_count;
    while (lo < hi) {
        const ReUSize mid = lo + (hi - lo) / 2;
        if (catalog_table[mid].value_address < value_address) lo = mid + 1;
        else if (catalog_table[mid].value_address > value_address) hi = mid;
        else return &catalog_table[mid];
    }
    return nullptr;
}

const ConfigKeyEntry* config_lookup_name(re::ReStringView name) {
    for (ReUSize i = 0; i < catalog_count; ++i)
        if (catalog_table[i].name == name) return &catalog_table[i];
    return nullptr;
}

void check_config_catalog() {
    const auto span = config_catalog();
    if (span.size() != 1066) __builtin_trap();

    // [C] Verify sort order
    for (ReUSize i = 1; i < span.size(); ++i)
        if (span[i].value_address <= span[i-1].value_address) __builtin_trap();

    // [C] Verify known key lookups
    const auto* psilent = config_lookup(0x3d7e78);
    if (!psilent || psilent->name != "Bools.PSilent") __builtin_trap();
    if (psilent->type != config_bool || psilent->dead) __builtin_trap();

    const auto* special_tp = config_lookup(0x3f7e48);
    if (!special_tp || special_tp->name != "Bools.SpecialTeleport") __builtin_trap();

    const auto* proj_speed = config_lookup(0x3d80a8);
    if (!proj_speed || proj_speed->name != "F.projectilespeed") __builtin_trap();
    if (proj_speed->type != config_float) __builtin_trap();

    const auto* player_dist = config_lookup(0x3d8148);
    if (!player_dist || player_dist->name != "i.PlayerMaxDistance") __builtin_trap();
    if (player_dist->type != config_int) __builtin_trap();

    const auto* by_name = config_lookup_name("Bools.Pierce");
    if (!by_name || by_name->value_address != 0x3d7ec8) __builtin_trap();

    // [C] Verify dead key example
    const auto* dead_key = config_lookup_name("Bools.AimPrediction");
    if (!dead_key || !dead_key->dead) __builtin_trap();

    // [I] Count verification
    ReUSize active = 0, dead = 0;
    for (ReUSize i = 0; i < span.size(); ++i) {
        if (span[i].dead) ++dead; else ++active;
    }
    if (active != 676 || dead != 390) __builtin_trap();
}
